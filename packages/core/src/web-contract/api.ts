/** The request and response shapes of the local web API (`specs/web-app/api-surface.md`), delivery step 1. */
import type { RunSnapshot, RunSummary } from './run.js';

/** The version of the contract between the page and the server. */
export interface ContractResponse {
  readonly contractVersion: string;
}

export interface ApiError {
  readonly code: string;
  /** Plain words a person can act on; never a secret, a path or a URL. */
  readonly message: string;
  readonly nextAction?: string;
  /** For settings that were refused: one plain sentence per problem, each naming its key. */
  readonly problems?: readonly string[];
}

export interface RunListResponse {
  readonly runs: readonly RunSummary[];
}

/** One message of a debate, as the engine kept it: redacted, with control sequences dropped. */
export interface DiscussionMessage {
  readonly round: number;
  readonly sender: string;
  /** PROPOSAL, CRITIQUE, AGREEMENT or any other type the debate used. */
  readonly type: string;
  readonly content: string;
}

/** The ruling that settled a debate which did not reach quorum. */
export interface DiscussionRuling {
  readonly verdict: string;
  readonly decidedBy: string;
  readonly note: string;
}

/** The whole discussion of one debate step of one run. */
export interface DiscussionView {
  readonly stepId: string;
  readonly outcome: string;
  readonly rounds: number;
  readonly messages: readonly DiscussionMessage[];
  readonly ruling?: DiscussionRuling;
}

export interface DiscussionResponse {
  readonly discussion: DiscussionView;
}

export interface RunResponse {
  readonly run: RunSnapshot;
  /** True only while a run this server started is alive, so the page offers Stop (contract 1.1). */
  readonly canStop: boolean;
}

/** One workflow file found in a served root. */
export interface WorkflowSummary {
  /** Opaque. The page sends it back; it is matched against a fresh scan, never opened as a path. */
  readonly id: string;
  readonly name: string;
  /** Relative to its root, forward slashes. */
  readonly path: string;
  /** The root's folder name, to tell two projects apart. */
  readonly project: string;
  readonly valid: boolean;
  /** One plain sentence per problem, as `indaba validate` words them; empty when valid. */
  readonly problems: readonly string[];
}

export interface WorkflowListResponse {
  readonly workflows: readonly WorkflowSummary[];
  /** True when the scan stopped at its limits, so the list may be incomplete. */
  readonly truncated: boolean;
}

/** What a first run will use, as the workflow file declares it. Text only; each item cut to a bounded length. */
export interface RunSummaryOfUse {
  /** The runner of every step, by name. */
  readonly runners: readonly string[];
  /** `shell` command lines, every `agent.command`, every local MCP server command. */
  readonly commands: readonly string[];
  /** One line per step; a step that declares none reads "runner default (unrestricted)". */
  readonly permissions: readonly string[];
  /** Steps that need a person (`arbiter: human`); they end escalated, because the run has no terminal. */
  readonly needsPerson: readonly string[];
}

export interface StartRunRequest {
  readonly workflowId: string;
  /** The `contentHash` of a `confirmation_required` answer, to confirm that content. */
  readonly confirmedHash?: string;
}

export interface StartRunResponse {
  /** The task id, generated by the server. Poll `GET /starts/{startId}` for the run. */
  readonly startId: string;
}

export interface ConfirmationRequired extends ApiError {
  readonly code: 'confirmation_required';
  readonly contentHash: string;
  readonly use: RunSummaryOfUse;
}

export interface StartStatusResponse {
  readonly state: 'starting' | 'running' | 'failed';
  /** The trace id, once the engine has opened the trace; what `GET /runs/{id}` takes. */
  readonly runId?: string;
  /** For `failed`: the first line of the child's error stream, redacted and sanitised. */
  readonly failure?: string;
}

export interface StopRunResponse {
  readonly state: 'stopping' | 'ended';
}

/**
 * One event of a run's stream. The server builds the snapshot with the same reducer the terminal dashboard uses
 * and sends the whole snapshot, so a repeated or a missed event cannot corrupt the page: `id` only rises.
 */
export interface RunStreamEvent {
  readonly id: number;
  readonly run: RunSnapshot;
}

/** A run that appeared or ended, on the server-wide stream. */
export interface ServerStreamEvent {
  readonly id: number;
  readonly kind: 'run_started' | 'run_ended';
  readonly run: RunSummary;
}

/** One problem of a workflow text, as `indaba validate` words it (contract 1.2). */
export interface WorkflowProblem {
  readonly message: string;
  /** 1-based, where the problem is placed in the text; absent when not even its root could be placed. */
  readonly line?: number;
  readonly column?: number;
  /** The place the sentence is about, as the parser writes it (`$.steps[0].role`); added in contract 1.3. */
  readonly path?: string;
}

export interface WorkflowSourceResponse {
  readonly workflow: WorkflowSummary;
  readonly text: string;
  /** SHA-256 of the file's bytes, lowercase hex: the `baseHash` of a later save. */
  readonly contentHash: string;
  readonly problems: readonly WorkflowProblem[];
}

export interface SaveWorkflowSourceRequest {
  readonly text: string;
  readonly baseHash: string;
}

export interface SaveWorkflowSourceResponse {
  readonly contentHash: string;
  readonly problems: readonly WorkflowProblem[];
}

export interface WorkflowChangedOnDisk extends ApiError {
  readonly code: 'changed_on_disk';
  readonly current: { readonly text: string; readonly contentHash: string };
}

export interface CheckWorkflowRequest {
  readonly text: string;
}

export interface WorkflowCheckResponse {
  readonly problems: readonly WorkflowProblem[];
}

/** A value as JSON carries it (contract 1.3, specs/web-app-editing-forms). */
export type JsonValue = null | boolean | number | string | readonly JsonValue[] | JsonObject;
export interface JsonObject {
  readonly [key: string]: JsonValue;
}

/** Keys and indexes from the root of a workflow file: `['steps', 0, 'role']`. */
export type WorkflowPath = readonly (string | number)[];

/** One change of a workflow text, as `WorkflowDocument` of `@indaba/engine` makes it. */
export type WorkflowEdit =
  | { readonly op: 'set'; readonly path: WorkflowPath; readonly value: JsonValue }
  | { readonly op: 'remove'; readonly path: WorkflowPath }
  | { readonly op: 'addStep'; readonly step: JsonObject; readonly after?: string }
  | { readonly op: 'removeStep'; readonly id: string }
  | { readonly op: 'moveStep'; readonly id: string; readonly after?: string };

export interface EditWorkflowRequest {
  readonly text: string;
  /** Applied in order; empty reads the text without changing it. */
  readonly edits: readonly WorkflowEdit[];
}

export interface WorkflowEditResponse {
  /** The text after the edits. */
  readonly text: string;
  /** The document as plain JSON: what the form shows. */
  readonly value: JsonObject;
  /** The problems of `text`, as the check gives them, each with its `path`. */
  readonly problems: readonly WorkflowProblem[];
}

/** `422`: the text cannot be read as a workflow document. */
export interface WorkflowNotEditable extends ApiError {
  readonly code: 'not_editable';
}

/** `422`: one edit was refused; nothing was changed. */
export interface WorkflowEditRefused extends ApiError {
  readonly code: 'edit_refused';
  /** The index in `edits` of the edit refused. */
  readonly index: number;
  /** The path the refusal is about, when it is about one. */
  readonly path?: string;
}

/** A name and one line, as the catalog lists a runner, a guard type or an arbiter. */
export interface CatalogEntry {
  readonly name: string;
  readonly description: string;
}

/** What this installation offers a workflow: `Catalog` of `@indaba/engine`, version 1, as the page receives it. */
export interface EditorCatalog {
  readonly catalog: 1;
  readonly runners: readonly CatalogEntry[];
  readonly guards: readonly CatalogEntry[];
  readonly arbiters: readonly CatalogEntry[];
  readonly voters: readonly CatalogEntry[];
  readonly prompts: readonly CatalogEntry[];
  readonly values: {
    readonly decisionTypes: readonly string[];
    readonly isolation: readonly string[];
    readonly failureActions: readonly string[];
    readonly mcpPolicies: readonly string[];
    readonly promptAdditions: readonly string[];
  };
}

export interface EditorResponse {
  /** `workflowJsonSchema()`: JSON Schema draft 2020-12 of the workflow file. */
  readonly schema: JsonObject;
  readonly catalog: EditorCatalog;
}
